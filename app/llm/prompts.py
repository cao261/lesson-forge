def build_transcript_context(cues: list, lo: float, hi: float, limit: int = 12) -> str:
    """截取某个时间点前后的字幕，用作看图转写时的语境。"""
    picked = [c for c in cues if c.end >= lo - 20 and c.start <= hi + 30]
    picked = picked[:limit]
    return " / ".join(f"[{fmt_ts(c.start)}] {c.text}" for c in picked)


def knowledge_for_prompt(kps: list) -> str:
    """把知识点+例题转成给模型看的文本块。"""
    chunks: list[str] = []
    for kp in kps:
        chunks.append(f"### {kp.id}｜{kp.title}  [{fmt_ts(kp.ts_start)}–{fmt_ts(kp.ts_end)}]")
        chunks.append(f"- 摘要：{kp.summary}")
        if kp.definition:
            chunks.append(f"- 定义/结论：{kp.definition}")
        if kp.formula_latex:
            chunks.append(f"- 核心公式：{kp.formula_latex}")
        if kp.key_points:
            chunks.append("- 要点：" + "；".join(kp.key_points))
        if kp.pitfalls:
            chunks.append("- 易错：" + "；".join(kp.pitfalls))
        if kp.source_quote:
            chunks.append(f"- 字幕原句：{kp.source_quote}")
        if kp.examples:
            chunks.append(f"- 本节例题 {len(kp.examples)} 道：")
            for ex in kp.examples:
                chunks.append(
                    f"  - id={ex.id}｜{ex.title}｜时间戳 {fmt_ts(ex.ts_start)}–{fmt_ts(ex.ts_end)}"
                    f"｜截图文件={ex.shot or '（未获取到）'}"
                )
                chunks.append(f"    - 题干：{ex.statement_latex or ex.statement_plain or '（未转写成功）'}")
        chunks.append("")
    return "\n".join(chunks)